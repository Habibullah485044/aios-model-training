#!/usr/bin/env python3
"""build_kernels.py - generate the two Kaggle kernel bundles from the sources.

Reads (relative to training/native):
    kernel/export_weights.py, runtime/aios_infer.c,
    compile_check/compile_check.py, real_check/real_check.py
Writes (relative to this file):
    kaggle/aios-native-compile-check/{kernel-metadata.json, main.py}
    kaggle/aios-native-real-check/{kernel-metadata.json, main.py}

Each main.py re-materializes the sources under /kaggle/working/training/native
and runs the harness. Run this after any edit to the four source files.
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.dirname(HERE)
OWNER = "habibullah6666666888"


def corpus(rel_dir):
    """Corpus sources of a pass check, sorted, as native-relative paths."""
    out = []
    for path in sorted(glob.glob(os.path.join(NATIVE, rel_dir, "*.s"))):
        out.append(os.path.join(rel_dir, os.path.basename(path)).replace(
            os.sep, "/"))
    return out


def corpus_tree(rel_dir):
    """Like corpus(), but recursive: B3's corpus is per-program subdirs."""
    out = []
    for path in sorted(glob.glob(os.path.join(NATIVE, rel_dir, "*", "*.s"))):
        out.append(os.path.relpath(path, NATIVE).replace(os.sep, "/"))
    return out


def read(rel):
    with open(os.path.join(NATIVE, rel), "r", encoding="utf-8") as f:
        return f.read()


def make_main(harness_rel, harness_run, extras=()):
    files = {
        "kernel/export_weights.py": read("kernel/export_weights.py"),
        "runtime/aios_infer.c": read("runtime/aios_infer.c"),
        harness_rel: read(harness_rel),
    }
    for extra in extras:
        files[extra] = read(extra)
    lines = [
        "#!/usr/bin/env python3",
        "# GENERATED by build_kernels.py - do not edit; edit the sources and regenerate.",
        "import os, subprocess, sys",
        "",
        "ROOT = '/kaggle/working/training/native'",
        "FILES = " + json.dumps(files) + "",
        "",
        "for rel, content in FILES.items():",
        "    path = os.path.join(ROOT, rel)",
        "    os.makedirs(os.path.dirname(path), exist_ok=True)",
        "    with open(path, 'w', encoding='utf-8') as f:",
        "        f.write(content)",
        "",
        "os.environ['AIOS_TMP'] = '/tmp/aios_native'",
        "sys.path.insert(0, os.path.join(ROOT, 'kernel'))",
        "print('running: ' + ' '.join(" + json.dumps(harness_run) + "), flush=True)",
        "r = subprocess.run([sys.executable] + " + json.dumps(harness_run) + ", cwd=ROOT)",
        "sys.exit(r.returncode)",
        "",
    ]
    return "\n".join(lines)


def make_bundle(name, title, harness_rel, harness_run, gpu, extras=()):
    d = os.path.join(HERE, name)
    os.makedirs(d, exist_ok=True)
    meta = {
        "id": "%s/%s" % (OWNER, name),
        "title": title,
        "code_file": "main.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
    }
    with open(os.path.join(d, "kernel-metadata.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)
        f.write("\n")
    with open(os.path.join(d, "main.py"), "w", encoding="utf-8") as f:
        f.write(make_main(harness_rel, harness_run, extras))
    print("wrote", d)


def main():
    make_bundle(
        "aios-native-compile-check",
        "aios-native-compile-check",
        "compile_check/compile_check.py",
        ["compile_check/compile_check.py"],
        gpu=False,
    )
    make_bundle(
        "aios-native-real-check",
        "aios-native-real-check",
        "real_check/real_check.py",
        ["real_check/real_check.py"],
        gpu=False,
        # Phase 1 measures, Phase 2 packs, and both run inside this same
        # kernel so they reuse the weights.bin that real_check just
        # exported -- no extra model download, no stale /tmp.
        # Phase 3 (A2) races the kernels on that same packed data;
        # Phase 4 (A4) checks the packed oracle vs the BF16 oracle.
        extras=("phase1/measure.py", "phase2/phase2_check.py", "phase2/pack.py",
                "phase2/unpack_ref.c", "phase3/race_check.py", "phase3/race.c",
                "phase4/phase4_check.py", "a3/bench.c", "a3/make_a3bench_data.py",
                "a3/a3_pack_check.py"),
    )
    make_bundle(
        "aios-native-a3build",
        "aios-native-a3build",
        "a3/a3_pack_check.py",
        ["a3/a3_pack_check.py"],
        gpu=False,
        # Fast A3 iteration kernel: zig-builds the old-PC benchmark exes,
        # runs the static PE scans, and packages a synthetic-data zip.
        # No model download - used to shake out compile/scan failures
        # before spending an hour on the full real-check chain.
        extras=("a3/bench.c", "a3/make_a3bench_data.py", "phase2/pack.py"),
    )
    make_bundle(
        "aios-native-partb",
        "aios-native-partb",
        "partb/run_all.py",
        ["partb/run_all.py"],
        gpu=False,
        # Part B pass checks run on Kaggle Linux (file/readelf/objdump,
        # GNU as, executing the ELF files). Python only builds and tests.
        # grid_probe.py is the auto-generated differential grid that
        # Part B's B2 step runs after b2_check.py (D-023).
        extras=("b1/elf64_writer.py", "b1/b1_check.py",
                "b2/asm.py", "b2/b2_check.py", "b2/grid_probe.py",
                "b3/link.py", "b3/b3_check.py",
                "b4/runtime.s", "b4/b4_check.py") + tuple(
                    corpus("b2/corpus")) + tuple(corpus_tree("b3/corpus"))
                + tuple(corpus_tree("b4/corpus")),
    )


if __name__ == "__main__":
    main()
